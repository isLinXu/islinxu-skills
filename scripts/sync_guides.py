#!/usr/bin/env python3
"""Generate Claude Code and Cursor entry points from surgical-coding/SKILL.md."""

from __future__ import annotations

import argparse
from pathlib import Path

from validate_repo import parse_frontmatter

SKILL_PATH = Path("skills/surgical-coding/SKILL.md")
CLAUDE_PATH = Path("CLAUDE.md")
CURSOR_PATH = Path(".cursor/rules/surgical-coding.mdc")
GENERATED_NOTE = "<!-- GENERATED by scripts/sync_guides.py; edit skills/surgical-coding/SKILL.md instead. -->"


def render_guides(root: Path) -> dict[Path, str]:
    """Render all secondary guides without touching the filesystem."""
    fields, body = parse_frontmatter(root / SKILL_PATH)
    claude_body = body.replace("](references/", "](skills/surgical-coding/references/")
    cursor_body = body.replace("](references/", "](../../skills/surgical-coding/references/")
    claude = (
        "# CLAUDE.md\n\n"
        f"{GENERATED_NOTE}\n\n"
        "阅读 [AGENTS.md](AGENTS.md) 中的仓库约定。以下规则用于编码、修复、重构和代码审查；"
        "简单任务按风险裁剪流程。\n\n"
        f"{claude_body}"
    )
    cursor = (
        "---\n"
        f"description: {fields['description']}\n"
        "alwaysApply: true\n"
        "---\n\n"
        f"{GENERATED_NOTE}\n\n"
        f"{cursor_body}"
    )
    return {CLAUDE_PATH: claude, CURSOR_PATH: cursor}


def sync_guides(root: Path, *, check: bool = False) -> list[str]:
    """Write generated guides or return stale paths without modifying them."""
    stale = []
    for relative, expected in render_guides(root).items():
        destination = root / relative
        if not destination.is_file() or destination.read_text(encoding="utf-8") != expected:
            stale.append(str(relative))
            if not check:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(expected, encoding="utf-8")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="fail if generated guides are missing or stale")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        stale = sync_guides(root, check=args.check)
    except (OSError, UnicodeError, ValueError) as exc:
        parser.error(str(exc))
    if stale and args.check:
        for relative in stale:
            print(f"STALE {relative}")
        print("Run python scripts/sync_guides.py to regenerate entry points.")
        return 1
    if stale:
        for relative in stale:
            print(f"WROTE {relative}")
    else:
        print("Generated guides are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
